import { access, cp, mkdir, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'Web');
const destination = path.join(root, 'dist');
const marker = path.join(destination, '.yumi-web-build');

let generated = false;
try { await access(marker); generated = true; } catch { /* no marker yet */ }
if (generated) {
  await rm(destination, { recursive: true, force: true });
} else {
  try {
    await access(destination);
    throw new Error('dist/ exists but is not marked as generated by this project');
  } catch (error) {
    if (error.message.includes('not marked')) throw error;
  }
}
await mkdir(destination, { recursive: true });
await cp(source, destination, { recursive: true });
await writeFile(marker, 'generated by npm run build\n');
console.log(`Web app built into ${path.relative(root, destination)}`);
